"""Read compare/ablation/sweep JSONL outputs and emit a markdown report.

Usage:

    .venv/bin/python -m concord.experiments.aggregate \\
        --compare-dir results/concord/compare \\
        --ablation-dir results/concord/ablation \\
        --sweep-summary results/concord/sweep/sweep_summary.jsonl \\
        --out RESULTS.md

The report answers the two §10 questions head-on:
  1. Does Concord beat B2 (v1) on solve@budget at equal or lower cost?
  2. Does SD improve U_s calibration (AUROC) over the cosine ablation?

Missing inputs are tolerated — the relevant section says so explicitly.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from experiments.metrics import RunRecord, auroc, ece, summarize


# ---------------------------------------------------------------------------

def _load_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def _row_to_record(row: dict) -> RunRecord | None:
    if "error" in row:
        return None
    cost = row.get("cost", {})
    return RunRecord(
        question_id=row.get("question_id", ""),
        correct=row.get("correct"),
        coherent=row.get("coherent", False),
        sigma=row.get("sigma", 1.0),
        rollouts=row.get("rollouts", 0),
        calls=cost.get("calls", 0),
        tokens_in=cost.get("input_tokens", 0),
        tokens_out=cost.get("output_tokens", 0),
        usd=cost.get("usd", 0.0),
        elapsed_s=row.get("elapsed_s", 0.0),
        u_s_sample=row.get("u_s_sample"),
    )


def _fmt_pct(x: float) -> str:
    if isinstance(x, float) and math.isnan(x):
        return "—"
    return f"{x:.1%}"


def _fmt_acc_cost(arm_name: str, s: dict) -> str:
    return (f"| {arm_name} | "
            f"{_fmt_pct(s['accuracy'])} | "
            f"{_fmt_pct(s['coherence_rate'])} | "
            f"{s['rollouts_mean']:.1f} | "
            f"{s['cost']['calls']} | "
            f"${s['cost']['usd']:.4f} |")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--compare-dir", type=Path,
                   default=Path("results/concord/compare"))
    p.add_argument("--ablation-dir", type=Path,
                   default=Path("results/concord/ablation"))
    p.add_argument("--sweep-summary", type=Path,
                   default=Path("results/concord/sweep/sweep_summary.jsonl"))
    p.add_argument("--out", type=Path, default=Path("RESULTS.md"))
    args = p.parse_args()

    lines: list[str] = []
    add = lines.append
    add("# Concord — Results report\n")
    add("Generated by `concord/experiments/aggregate.py`.\n")

    # ------------------------------------------------------------------
    # Section: comparison Concord vs baselines (§10 criterion 5, question 1)
    # ------------------------------------------------------------------
    add("## 1. Concord vs baselines (solve@budget @ equal cost)\n")
    summaries: dict[str, dict] = {}
    if args.compare_dir.is_dir():
        for path in sorted(args.compare_dir.glob("*.jsonl")):
            arm = path.stem
            rows = _load_jsonl(path)
            recs = [r for r in (_row_to_record(r) for r in rows) if r is not None]
            if recs:
                summaries[arm] = summarize(recs)
    if summaries:
        add("| arm | accuracy | coherence | rollouts (mean) | calls | $ |")
        add("|---|---|---|---|---|---|")
        for arm in sorted(summaries):
            add(_fmt_acc_cost(arm, summaries[arm]))
        if "concord" in summaries and "b2_concord_v1" in summaries:
            v2 = summaries["concord"]; v1 = summaries["b2_concord_v1"]
            same_or_lower_cost = v2["cost"]["calls"] <= v1["cost"]["calls"]
            beats = (not (isinstance(v2["accuracy"], float)
                          and math.isnan(v2["accuracy"]))
                     and not (isinstance(v1["accuracy"], float)
                              and math.isnan(v1["accuracy"]))
                     and v2["accuracy"] > v1["accuracy"])
            verdict = ("**Concord beats v1 on solve@budget at equal-or-lower cost.**"
                       if beats and same_or_lower_cost else
                       "Concord does NOT beat v1 under these conditions.")
            add("")
            add(verdict)
            add(f"- Concord accuracy: {_fmt_pct(v2['accuracy'])}, v1 accuracy: {_fmt_pct(v1['accuracy'])}.")
            add(f"- Concord calls: {v2['cost']['calls']}, v1 calls: {v1['cost']['calls']} (lower-or-equal = {same_or_lower_cost}).")
    else:
        add("_No compare data found_ — run `experiments/compare.py` first.")
    add("")

    # ------------------------------------------------------------------
    # Section: SD calibration vs cosine_centroid ablation (question 2)
    # ------------------------------------------------------------------
    add("## 2. SD vs cosine_centroid (U_s calibration: AUROC, ECE)\n")
    v2_sum = summaries.get("concord")
    abl_cosine: dict | None = None
    if args.ablation_dir.is_dir():
        cosine_summary = args.ablation_dir / "cosine_centroid_summary.json"
        if cosine_summary.exists():
            abl_cosine = json.loads(cosine_summary.read_text())
    if v2_sum and abl_cosine:
        a_v2 = v2_sum["calibration"]
        a_co = abl_cosine["calibration"]
        add(f"- Concord (SD): AUROC={a_v2.get('auroc')}, ECE={a_v2.get('ece')} "
            f"(n={a_v2.get('n_calibration_points')})")
        add(f"- ablation cosine_centroid: AUROC={a_co.get('auroc')}, ECE={a_co.get('ece')} "
            f"(n={a_co.get('n_calibration_points')})")
    else:
        add("_Calibration comparison not available_ — needs both `compare/concord.jsonl` "
            "and `ablation/cosine_centroid_summary.json`.")
    add("")

    # ------------------------------------------------------------------
    # Section: §8.4 ablation table
    # ------------------------------------------------------------------
    add("## 3. §8.4 ablations\n")
    abl_rows: list[tuple[str, dict]] = []
    if args.ablation_dir.is_dir():
        for path in sorted(args.ablation_dir.glob("*_summary.json")):
            data = json.loads(path.read_text())
            arm = data.get("arm", path.stem)
            abl_rows.append((arm, data))
    if abl_rows:
        add("| ablation | accuracy | coherence | calls | AUROC | ECE |")
        add("|---|---|---|---|---|---|")
        for arm, data in abl_rows:
            cal = data.get("calibration", {})
            add(f"| {arm} | {_fmt_pct(data.get('accuracy', float('nan')))} | "
                f"{_fmt_pct(data.get('coherence_rate', float('nan')))} | "
                f"{data.get('cost', {}).get('calls', 0)} | "
                f"{cal.get('auroc')} | {cal.get('ece')} |")
    else:
        add("_No ablation summaries found_ — run `experiments/ablate.py` per arm.")
    add("")

    # ------------------------------------------------------------------
    # Section: sweep
    # ------------------------------------------------------------------
    add("## 4. Calibration sweep (c_puct, n_min, K)\n")
    sweep = _load_jsonl(args.sweep_summary)
    if sweep:
        add("| c_puct | n_min | K | accuracy | coherence | calls |")
        add("|---|---|---|---|---|---|")
        for s in sweep:
            add(f"| {s.get('c_puct')} | {s.get('n_min')} | {s.get('K')} | "
                f"{_fmt_pct(s.get('accuracy', float('nan')))} | "
                f"{_fmt_pct(s.get('coherence_rate', float('nan')))} | "
                f"{s.get('cost', {}).get('calls', 0)} |")
    else:
        add("_No sweep data found_ — run `experiments/sweep.py`.")
    add("")

    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
